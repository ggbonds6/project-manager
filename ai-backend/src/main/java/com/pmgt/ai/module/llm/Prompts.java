    /**
     * 把"当前可问答的文档清单"注入 system，减少模型盲目试探。
     *
     * <p>⚠️ 输出的 markdown 表格（{@code doc_id | 文件名 | 页数}）与 Python 版<b>逐字符一致</b>——
     * 这是替代 {@code list_documents} 工具的机制（工具集只剩 3 个，文档清单靠它注入 system 提示词）。
     */
    public static String buildDocScopeNote(List<Map<String, Object>> docs) {
        if (docs == null || docs.isEmpty()) {
            return "**当前没有已上传的文档。**请提示用户先上传文件。";
        }
        StringBuilder out = new StringBuilder();
        out.append("当前可检索的文档共 ").append(docs.size()).append(" 份：\n");
        out.append("\n");
        out.append("| doc_id | 文件名 | 页数 |\n");
        out.append("| --- | --- | --- |\n");
        for (Map<String, Object> doc : docs) {
            out.append("| `").append(str(doc.get("doc_id"))).append("` | ")
                    .append(str(doc.get("filename"))).append(" | ")
                    .append(str(doc.get("pages"))).append(" |\n");
        }
        out.append("\n");
        out.append("回答时优先检索这些文档；用户的问题若明显只涉及某一份，"
                + "可在 `search_documents` 里指定 `doc_id`。");
        return out.toString();
    }

