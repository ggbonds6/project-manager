/**
 * 提示词集中管理。
 *
 * <p><b>为什么单独成类</b>：本项目多个环节都要调大模型，而"不许编、必须标来源"
 * 这类硬约束必须<b>一处修改、处处生效</b>，也便于审计复核（政务/审计场景要求
 * 每个环节可解释、可追溯）。
 *
 * <h2>三条硬约束（用户明确要求，任何改动不得放松）</h2>
 *
 * <ol>
 *   <li><b>来源可溯</b>：每条信息必须标注页码出处，没有来源的信息不得输出；</li>
 *   <li><b>禁止虚构</b>：只允许使用原文内容，原文没有就写「原文未提及」，
 *       尤其是金额/日期/编号/人名/单位名；</li>
 *   <li><b>显式置信度</b>：每条信息给出 0.00–1.00 的置信度，并明确分档含义，
 *       禁止一律给高分。</li>
 * </ol>
 *
 * <h2>设计要点（为什么这么写）</h2>
 *
 * <ul>
 *   <li><b>给出分档标准</b>而不是"请评估置信度"：否则模型会一律回 0.95+，失去意义；</li>
 *   <li><b>明确"低分不算失败，编造才算"</b>：消除模型"不敢给低分"的倾向；</li>
 *   <li><b>数字要求原样照抄</b>：禁止换算/规范化——审计场景里"善意修正"等于篡改；
 *       可疑数字要<b>指出</b>而不是<b>改掉</b>；</li>
 *   <li><b>固定章节结构</b>：便于前端稳定渲染、便于人工逐栏核对；</li>
 *   <li><b>保留"存疑与未提及项"章节</b>：把"不知道"变成显式输出，而不是沉默地猜。</li>
 * </ul>
 *
 * <p>⚠️ <b>本类的中文文案逐字照搬 {@code ai-service/src/pm_ai/prompts.py}，一个字都不要改</b>
 * （它们是反复调试出来的：来源标注、禁止虚构、置信度三条铁律）。
 * Python 里用 f-string / {@code %} 格式化的地方改成 Java 拼接，语义与输出必须一致。
 */
