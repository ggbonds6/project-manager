    public static final String NO_INSTRUCTION = "（用户未指定特别关注点，请按文档类型自行判断应抽取哪些关键信息。）";

    /**
     * 组装用户提示词。
     *
     * @param labeledText   <b>带页码标记</b>的原文（见 {@code DocumentText.labeledText()}），
     *                      这是来源标注能落地的前提。
     * @param pageCount     原文总页数
     * @param instruction   用户特别关注点（可为空）
     * @param truncatedNote 截断说明（为空表示未截断）
     */
    public static String buildUserPrompt(
            String labeledText, int pageCount, String instruction, String truncatedNote) {
        String focus = instruction == null || instruction.strip().isEmpty()
                ? NO_INSTRUCTION
                : instruction.strip();
        String tail = truncatedNote == null || truncatedNote.isEmpty()
                ? "（原文共 " + pageCount + " 页，以上为全部内容。）"
                : "（原文共 " + pageCount + " 页。⚠️ " + truncatedNote + "）";

        return """
                ## 本次任务

                请从下面的【原文】中抽取信息，并严格按系统提示词中的铁律与格式输出。

                ### 用户特别关注

                """ + focus + """


                （请在「关键信息」中优先覆盖上述关注点；但上述铁律不变。）

                ---

                ## 原文

                """ + labeledText + """


                ---

                """ + tail + "\n";
    }

