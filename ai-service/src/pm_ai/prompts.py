"""提示词集中管理。

**为什么单独成文件**：本项目多个环节都要调大模型，而"不许编、必须标来源"
这类硬约束必须**一处修改、处处生效**，也便于审计复核（政务/审计场景要求
每个环节可解释、可追溯）。

## 三条硬约束（用户明确要求，任何改动不得放松）

1. **来源可溯**：每条信息必须标注页码出处，没有来源的信息不得输出；
2. **禁止虚构**：只允许使用原文内容，原文没有就写「原文未提及」，
   尤其是金额/日期/编号/人名/单位名；
3. **显式置信度**：每条信息给出 0.00–1.00 的置信度，并明确分档含义，
   禁止一律给高分。

## 设计要点（为什么这么写）

- **给出分档标准**而不是"请评估置信度"：否则模型会一律回 0.95+，失去意义；
- **明确"低分不算失败，编造才算"**：消除模型"不敢给低分"的倾向；
- **数字要求原样照抄**：禁止换算/规范化——审计场景里"善意修正"等于篡改；
  可疑数字要**指出**而不是**改掉**；
- **固定章节结构**：便于前端稳定渲染、便于人工逐栏核对；
- **保留"存疑与未提及项"章节**：把"不知道"变成显式输出，而不是沉默地猜。
"""

from __future__ import annotations

