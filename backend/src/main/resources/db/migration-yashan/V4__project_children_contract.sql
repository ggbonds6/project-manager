-- 由 MySQL 版 V4__project_children_contract.sql 转换：
--   * ALTER ... ADD COLUMN ..., ADD KEY ... 拆为 ADD 列 + 表外 CREATE INDEX
--   * MySQL UPDATE t JOIN ... 改写为 Oracle 相关标量子查询 + ROWNUM=1
--   * 回填语句对全新空库执行影响 0 行，仅保留语义等价
