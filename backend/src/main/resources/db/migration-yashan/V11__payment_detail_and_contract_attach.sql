-- 5) 历史附件归位：attach_type=CONTRACT 的附件原本挂在项目/阶段上，
--    统一改挂到 biz_type=CONTRACT + biz_id=合同id（合同多了以后必须能分辨属于哪份）
--
-- 约定（与既有迁移一致）：
--   * 主键 BIGINT GENERATED BY DEFAULT AS IDENTITY
--   * 字符列一律 VARCHAR(n CHAR)
--   * 索引在表外单独 CREATE INDEX
--   * 字典统一存 dict_item(dict_type, code, name, sort_no)，配色在
--     frontend/src/config/tagDict.ts 维护（不落库）
-- ============================================================

