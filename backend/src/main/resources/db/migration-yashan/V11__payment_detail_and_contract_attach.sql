-- ── 5) 合同附件归位：项目级 / 阶段级 → 合同级 ─────────────────
-- 5a) 项目级合同附件：biz_id(项目) → 该项目的合同 id
UPDATE attachment a
SET a.biz_id = (SELECT p.contract_id FROM project p WHERE p.id = a.biz_id AND ROWNUM = 1)
WHERE a.attach_type = 'CONTRACT'
  AND a.biz_type = 'PROJECT'
  AND EXISTS (SELECT 1 FROM project p WHERE p.id = a.biz_id AND p.contract_id IS NOT NULL);

UPDATE attachment a
SET a.biz_type = 'CONTRACT'
WHERE a.attach_type = 'CONTRACT'
  AND a.biz_type = 'PROJECT'
  AND EXISTS (SELECT 1 FROM contract c WHERE c.id = a.biz_id);

-- 5b) 阶段级合同附件：biz_id(阶段) → 阶段所属项目的合同 id
UPDATE attachment a
SET a.biz_id = (SELECT p.contract_id
                FROM project_phase ph, project p
                WHERE ph.id = a.biz_id AND p.id = ph.project_id AND ROWNUM = 1)
WHERE a.attach_type = 'CONTRACT'
  AND a.biz_type = 'PROJECT_PHASE'
  AND EXISTS (SELECT 1 FROM project_phase ph, project p
              WHERE ph.id = a.biz_id AND p.id = ph.project_id AND p.contract_id IS NOT NULL);

UPDATE attachment a
SET a.biz_type = 'CONTRACT'
WHERE a.attach_type = 'CONTRACT'
  AND a.biz_type = 'PROJECT_PHASE'
  AND EXISTS (SELECT 1 FROM contract c WHERE c.id = a.biz_id);

-- 5c) 归属类型注释更新（新增 CONTRACT）
COMMENT ON COLUMN attachment.biz_type IS '归属类型 PROJECT_PHASE(阶段)/PAYMENT(付款)/PROJECT(项目)/CONTRACT(合同)';

